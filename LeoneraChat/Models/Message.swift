import Foundation

struct GeneratedImage: Codable, Hashable {
    /// The image as returned by the API.
    var full: StoredFile
    /// A lighter copy that is sent back to the API in later turns.
    var input: StoredFile
}

struct MessageError: Codable, Hashable {
    var message: String
    /// The API key was rejected.
    var auth = false
    /// The response is still on OpenAI's side: retrying resumes polling instead of starting over.
    var resumable = false
}

/// A message of the chat, or the result of a mini app.
struct Message: Codable, Identifiable, Hashable {
    enum Role: String, Codable {
        case user, assistant
    }

    enum Status: String, Codable {
        case pending, done, failed, cancelled
    }

    /// What a pending response is doing.
    enum Phase: String, Codable {
        case thinking, image
    }

    var id = UUID()
    var role: Role
    var text = ""
    /// The user's photos, already resized for the API.
    var photos: [StoredFile] = []
    /// The images the assistant generated.
    var images: [GeneratedImage] = []
    var status: Status = .done
    var startedAt = Date()
    /// The background response, once created.
    var responseId: String?
    /// The request and the response as they were sent and received, kept for mini apps to show.
    var rawRequest: StoredFile?
    var rawResponse: StoredFile?
    var phase: Phase?
    var notice: String?
    var error: MessageError?

    static func user(_ text: String, photos: [StoredFile]) -> Message {
        Message(role: .user, text: text, photos: photos)
    }

    /// A message waiting for its response, with nothing in it yet.
    static func pendingReply() -> Message {
        Message(role: .assistant, status: .pending, phase: .thinking)
    }

    var isPending: Bool { role == .assistant && status == .pending }

    /// Every stored file the message refers to.
    var files: [StoredFile] {
        photos + images.flatMap { [$0.full, $0.input] } + [rawRequest, rawResponse].compactMap { $0 }
    }
}

/// What the chat sends: the whole conversation, on every turn.
enum ChatRequest {
    /// Images generated by the assistant are included in the following user message, so the model can
    /// keep editing them.
    static func make(history: [Message], model: String, imageModel: String) async -> ResponseRequest {
        var input: [InputItem] = [.system(systemPrompt())]
        var generated: [StoredFile] = []

        for message in history {
            if message.role == .assistant {
                guard message.status == .done else { continue }
                if !message.text.isEmpty { input.append(.assistant(message.text)) }
                generated += message.images.map(\.input)
                continue
            }

            var content = (generated + message.photos).compactMap { file in
                (try? BlobStore.dataURL(for: file)).map(InputContent.image)
            }
            if !message.text.isEmpty { content.append(.text(message.text)) }
            input.append(.user(content))
            generated = []
        }

        return ResponseRequest(model: model, tools: [.init(model: imageModel)], input: input)
    }

    private static func systemPrompt() -> String {
        "You are Leonera Chat, a helpful assistant in an iPhone chat app. "
            + "Reply in the same language the user writes in. "
            + "Use Markdown when it improves readability. "
            + "Current date: \(PromptDate.today()). "
            + "You can create and edit images with your image generation tool. "
            + "Use it whenever the user asks you to create, draw, design, illustrate or modify an image. "
            + "Earlier images in the conversation (generated by you or attached by the user) are included in the user's messages, so you can edit them; "
            + "Generated images are shown to the user automatically: never include links or Markdown images for them, just add a brief comment."
    }
}

enum PromptDate {
    /// Like «Tuesday, 14 October 2026», always in English: the prompts are.
    static func today() -> String {
        let formatter = DateFormatter()
        formatter.locale = Locale(identifier: "en_US_POSIX")
        formatter.dateFormat = "EEEE, d MMMM yyyy"
        return formatter.string(from: Date())
    }
}
